<?php
/**
 * Plugin wiring.
 *
 * @package CCFO
 */

declare(strict_types=1);

namespace CCFO;

use CCFO\Engine\ContextFactory;
use CCFO\Engine\RequestLog;
use CCFO\Rules\RuleRepository;

/**
 * Holds the shared services and registers every module.
 */
final class Plugin {

	/**
	 * Instance.
	 *
	 * @var Plugin|null
	 */
	private static ?Plugin $instance = null;

	/**
	 * Rule storage.
	 *
	 * @var RuleRepository
	 */
	public readonly RuleRepository $rules;

	/**
	 * Context factory.
	 *
	 * @var ContextFactory
	 */
	public readonly ContextFactory $contexts;

	/**
	 * Request log.
	 *
	 * @var RequestLog
	 */
	public readonly RequestLog $log;

	/**
	 * Classic field module (also used by the field catalog).
	 *
	 * @var Classic\Fields
	 */
	public readonly Classic\Fields $fields;

	/**
	 * Constructor.
	 */
	private function __construct() {
		$this->rules    = new RuleRepository();
		$this->contexts = new ContextFactory();
		$this->log      = new RequestLog();
		$this->fields   = new Classic\Fields( $this );
	}

	/**
	 * Shared instance.
	 */
	public static function instance(): self {
		if ( null === self::$instance ) {
			self::$instance = new self();
		}
		return self::$instance;
	}

	/**
	 * Register hooks.
	 */
	public function boot(): void {
		$this->fields->register();
		( new Classic\Payments( $this ) )->register();
		( new Classic\Shipping( $this ) )->register();
		( new Classic\Validation( $this ) )->register();
		( new Classic\Assets( $this ) )->register();
		( new Orders( $this ) )->register();
		( new Tax\TaxRules( $this ) )->register();
		( new Blocks\StoreApi( $this ) )->register();
		( new Admin\RestController( $this ) )->register();

		self::when_blocks_loaded(
			function (): void {
				( new Blocks\Integration( $this ) )->register();
			}
		);

		if ( is_admin() ) {
			( new Admin\Menu() )->register();
			( new Admin\Notices() )->register();
		}
	}

	/**
	 * Run a callback once WooCommerce Blocks is loaded, also if that already happened.
	 *
	 * @param callable $callback Callback.
	 */
	public static function when_blocks_loaded( callable $callback ): void {
		if ( did_action( 'woocommerce_blocks_loaded' ) ) {
			$callback();
		} else {
			add_action( 'woocommerce_blocks_loaded', $callback );
		}
	}

	/**
	 * Plugin URL of a path.
	 *
	 * @param string $path Relative path.
	 */
	public static function url( string $path ): string {
		return plugins_url( $path, CCFO_FILE );
	}

	/**
	 * Asset metadata generated by @wordpress/scripts.
	 *
	 * @param string $name Entry name.
	 * @return array{dependencies: list<string>, version: string}
	 */
	public static function asset( string $name ): array {
		$file  = CCFO_DIR . "build/$name.asset.php";
		$asset = is_readable( $file ) ? require $file : [];
		return [
			'dependencies' => isset( $asset['dependencies'] ) && is_array( $asset['dependencies'] ) ? array_values( $asset['dependencies'] ) : [],
			'version'      => isset( $asset['version'] ) && is_string( $asset['version'] ) ? $asset['version'] : CCFO_VERSION,
		];
	}
}
